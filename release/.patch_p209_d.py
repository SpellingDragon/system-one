def main() -> int:
    text = TARGET.read_text(encoding="utf-8")
    for i, (old, new) in enumerate(PAIRS, start=1):
        n = text.count(old)
        assert n == 1, f"锚点 #{i} 命中 {n} 次（期望 1 次），不落盘：{old.splitlines()[1][:50]!r}"
    for old, new in PAIRS:
        text = text.replace(old, new, 1)
    for frag in ("# 白话：G3 表上", "# 白话：\"laya 中文会崩", "# 白话：这张表要摆的是"):
        assert frag not in text, f"该处仍未搬动：{frag!r}"
    TARGET.write_text(text, encoding="utf-8")
    print(f"[patch-d] 三处白话块搬进 docstring，行数 {len(text.splitlines())}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
